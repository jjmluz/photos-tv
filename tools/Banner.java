import java.awt.Font;
import java.awt.Shape;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.*;
import java.io.File;
import java.nio.file.Files;
import java.util.Locale;

/**
 * Writes the TV launcher banner: white card, pinwheel on the left, the app name as vector outlines.
 * Arguments: the Roboto font, the output file and the name (e.g. "Photos" or "Fotos").
 */
public class Banner {
    public static void main(String[] args) throws Exception {
        Font font = Font.createFont(Font.TRUETYPE_FONT, new File(args[0])).deriveFont(56f);
        FontRenderContext frc = new FontRenderContext(null, true, true);
        GlyphVector gv = font.createGlyphVector(frc, args[2]);
        Rectangle2D text = gv.getVisualBounds();

        double iconSize = 88;            // pinwheel diameter in banner units
        double gap = 22;
        double total = iconSize + gap + text.getWidth();
        double left = (320 - total) / 2;
        double iconCx = left + iconSize / 2, cy = 90;
        // Text: vertically centre its visual bounds on the card.
        double tx = left + iconSize + gap - text.getX();
        double ty = cy - (text.getY() + text.getHeight() / 2);

        Shape outline = AffineTransform.getTranslateInstance(tx, ty).createTransformedShape(gv.getOutline());
        StringBuilder d = new StringBuilder();
        double[] c = new double[6];
        for (PathIterator it = outline.getPathIterator(null); !it.isDone(); it.next()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO -> d.append(f("M%.2f,%.2f", c[0], c[1]));
                case PathIterator.SEG_LINETO -> d.append(f("L%.2f,%.2f", c[0], c[1]));
                case PathIterator.SEG_QUADTO -> d.append(f("Q%.2f,%.2f %.2f,%.2f", c[0], c[1], c[2], c[3]));
                case PathIterator.SEG_CUBICTO -> d.append(f("C%.2f,%.2f %.2f,%.2f %.2f,%.2f", c[0], c[1], c[2], c[3], c[4], c[5]));
                case PathIterator.SEG_CLOSE -> d.append("Z");
            }
        }

        // Pinwheel petals from ic_launcher_foreground (centre 54,54, radius 28), scaled to iconSize.
        double scale = iconSize / 56.0;
        String xml = """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- TV launcher banner, generated by tools/Banner.java from Roboto; edit and re-run that, not the paths. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                android:width="320dp" android:height="180dp"
                android:viewportWidth="320" android:viewportHeight="180">
                <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h320v180h-320z" />
                <group android:scaleX="%1$s" android:scaleY="%1$s" android:translateX="%2$s" android:translateY="%3$s">
                    <path android:fillColor="#FFEA4335" android:pathData="M54,54 L54,26 A14,14 0 0,1 54,54 Z" />
                    <path android:fillColor="#FFFBBC04" android:pathData="M54,54 L82,54 A14,14 0 0,1 54,54 Z" />
                    <path android:fillColor="#FF34A853" android:pathData="M54,54 L54,82 A14,14 0 0,1 54,54 Z" />
                    <path android:fillColor="#FF4285F4" android:pathData="M54,54 L26,54 A14,14 0 0,1 54,54 Z" />
                </group>
                <path android:fillColor="#FF3C4043" android:pathData="%4$s" />
            </vector>
            """.formatted(f("%.4f", scale), f("%.2f", iconCx - 54 * scale), f("%.2f", cy - 54 * scale), d);
        Files.writeString(new File(args[1]).toPath(), xml);
        System.out.println("text width " + Math.round(text.getWidth()) + ", path chars " + d.length());
    }

    static String f(String p, Object... a) { return String.format(Locale.ROOT, p, a); }
}
